@dataclass
class Course:
    tag: str
    cfg: dict
    lectures: list[Plan]
    exported: set[str]
    excluded: set[str]
    appendix: list[tuple[Plan, list[PlanItem]]]
    warnings: list[TexWarning]
    title: str
    subtitle: str


def handbook_root() -> Path:
    return roam.VAULT / "handbook"


def lectures_of(vault: Vault, course: str) -> list[Note]:
    ls = [n for n in vault.notes if "lecture" in n.tags and course in n.tags]
    return sorted(ls, key=lambda n: (n.date or "", n.created or ""))


def course_plan(vault: Vault, course: str) -> Course:
    cfg = vault.courses.get(course)
    if cfg is None:
        roam.die(f"курс «{course}» не описан в roam.toml")
    local: dict = {}
    p = handbook_root() / course / "handbook.toml"
    if p.is_file():
        local = tomllib.loads(p.read_text(encoding="utf-8"))
    excluded = {x.upper() for x in local.get("exclude", [])}
    warnings: list[TexWarning] = []
    lectures: list[Plan] = []
    for k, n in enumerate(lectures_of(vault, course), 1):
        plan, w = lecture_plan(n, vault)
        warnings += w
        if plan.number is None:
            plan.number = k
        elif plan.number != k:
            warnings.append(TexWarning(n.id, _rel(n), 0, "X13",
                                       f"в заголовке «Лекция {plan.number}», по дате это глава {k}"))
        lectures.append(plan)
    if not lectures:
        warnings.append(TexWarning("", course, 0, "X14", f"нет lecture-заметок с тегами lecture+{course}"))

    def ok(nid: str, where: str, line: int, plan: Plan) -> bool:
        n = vault.by_id.get(nid)
        if n is None:
            warnings.append(TexWarning(plan.note.id, _rel(plan.note), line, "X03", f"{where}: битая ссылка id:{nid[:8]}"))
            return False
        if nid in excluded:
            return False
        if vault.is_stub(n):
            warnings.append(TexWarning(plan.note.id, _rel(plan.note), line, "X07", f"{where}: заглушка «{n.title}» пропущена"))
            return False
        return True

    exported: set[str] = set()
    for plan in lectures:
        for s in plan.sections:
            s.items = [i for i in s.items if ok(i.id, "план", i.line, plan)]
            exported.update(i.id for i in s.items)
    appendix: list[tuple[Plan, list[PlanItem]]] = []
    seen = set(exported)
    for plan in lectures:
        items = []
        for i in plan.appendix:
            if i.id in seen or not ok(i.id, "вне конспекта", i.line, plan):
                continue
            seen.add(i.id)
            items.append(i)
        for x in local.get("extra_aux", []):
            x = x.upper()
            if x not in seen and x in vault.by_id and not vault.is_stub(vault.by_id[x]):
                seen.add(x)
                items.append(PlanItem(x, vault.by_id[x].title, None, 0))
        # transitive prerequisites: notes of this course linked only from
        # the appendix (or the plan) but not listed anywhere
        queue = [i.id for i in items] + plan.ids()
        while queue:
            src = vault.by_id.get(queue.pop(0))
            if src is None:
                continue
            for oid in src.out_ids():
                o = vault.by_id.get(oid)
                if (o is None or oid in seen or oid in excluded or vault.course_of(o) != course
                        or vault.is_stub(o) or set(o.tags) & {"lecture", "hub", "image"}):
                    continue
                seen.add(oid)
                items.append(PlanItem(oid, o.title, None, 0))
                queue.append(oid)
                warnings.append(TexWarning(o.id, _rel(o), 0, "X12",
                                           f"«{o.title}» не в плане, добавлена в приложение по ссылке из «{src.title}»"))
        if items:
            appendix.append((plan, items))
    exported = set(seen)
    for n in vault.notes:
        if (vault.course_of(n) == course and n.id not in exported and n.id not in excluded
                and not (set(n.tags) & {"lecture", "hub", "image"}) and not vault.is_stub(n)):
            warnings.append(TexWarning(n.id, _rel(n), 0, "X12", f"заметка курса вне плана: «{n.title}»"))
    return Course(course, cfg, lectures, exported, excluded, appendix, warnings,
                  local.get("title") or cfg.get("handbook_title") or cfg.get("name") or course,
                  local.get("subtitle") or "Конспект к экзамену по заметкам")


def _tex_str(s: str) -> str:
    return re.sub(r"(?<!\\)([%&#_~^$])", lambda m: _ESC[m.group(1)], s)


def render_course(vault: Vault, course: str) -> tuple[Course, dict[str, str], list[TexWarning]]:
    """Return (course, {relpath under handbook/: content}, warnings)."""
    c = course_plan(vault, course)
    warnings = list(c.warnings)
    files: dict[str, str] = {}
    macros = macros_latex(vault.cfg)
    files["common/macros.tex"] = macros

    for nid in sorted(c.exported):
        tex, w = note_to_tex(vault.by_id[nid], vault, c.exported)
        warnings += w
        files[f"{course}/notes/{nid}.tex"] = tex

    chapters = []
    for plan in c.lectures:
        nn = "%02d" % plan.number
        out = [GENERATED, f"% {plan.note.rel}", "",
               "\\chapter{%s}\\label{lecture:%d}" % (_tex_str(plan.title), plan.number),
               "\\InputIfFileExists{text/%s-intro}{}{}" % nn]
        for si, s in enumerate(plan.sections, 1):
            if s.title:
                out += ["", "\\section{%s}\\label{lecture:%d:%d}%s"
                        % (_tex_str(s.title), plan.number, si, f"  % конспект {s.ref}" if s.ref else ""),
                        "\\InputIfFileExists{text/%s-%d-intro}{}{}" % (nn, si)]
            for it in s.items:
                out += ["", "\\InputIfFileExists{text/%s-before}{}{}" % it.id,
                        "\\input{notes/%s}  %% %s%s" % (it.id, vault.by_id[it.id].title,
                                                       f" -- {it.annot}" if it.annot else "")]
        out += ["", "\\InputIfFileExists{text/%s-outro}{}{}" % nn, ""]
        files[f"{course}/chapters/{nn}.tex"] = "\n".join(out)
        chapters.append(nn)
    files[f"{course}/chapters.tex"] = "\n".join([GENERATED, ""] + ["\\input{chapters/%s}" % nn for nn in chapters] + [""])

    out = [GENERATED, "", "\\chapter{Вспомогательные утверждения}\\label{aux}",
           "\\InputIfFileExists{text/aux-intro}{}{}"]
    for plan, items in c.appendix:
        out += ["", "\\section{К лекции %d}\\label{aux:%d}" % (plan.number, plan.number)]
        for it in items:
            out += ["", "\\InputIfFileExists{text/%s-before}{}{}" % it.id,
                    "\\input{notes/%s}  %% %s%s" % (it.id, vault.by_id[it.id].title,
                                                   f" -- {it.annot}" if it.annot else "")]
    out.append("")
    files[f"{course}/aux.tex"] = "\n".join(out)

    files[f"{course}/meta.tex"] = "\n".join([
        GENERATED, "",
        "\\newcommand{\\handbooktitle}{%s}" % _tex_str(c.title),
        "\\newcommand{\\handbooksubtitle}{%s}" % _tex_str(c.subtitle),
        "\\newcommand{\\handbookcount}{%d}" % len(c.exported),
        "\\newcommand{\\handbooklectures}{%d}" % len(c.lectures), ""])
    return c, files, warnings


