def build(course: str, open_pdf: bool = False) -> int:
    d = handbook_root() / course
    if not (d / "main.tex").is_file():
        roam.die(f"нет {d / 'main.tex'} -- сначала handbook export", 1)
    if not shutil.which("latexmk"):
        roam.die("latexmk не найден (нужен TeX Live)", 1)
    cmd = ["latexmk", "-pdf", "-interaction=nonstopmode", "-synctex=1",
           "-r", "../.latexmkrc", "-outdir=build", "main.tex"]
    t0 = dt.datetime.now()
    proc = subprocess.run(cmd, cwd=d, capture_output=True, text=True)
    secs = (dt.datetime.now() - t0).total_seconds()
    log = d / "build" / "main.log"
    errors, undefined, overfull, multiply = [], [], 0, 0
    if log.is_file():
        L = log.read_text(encoding="utf-8", errors="replace").split("\n")
        for i, l in enumerate(L):
            if l.startswith("!"):
                ctxl = [x for x in L[i + 1:i + 6] if x.startswith("l.") or x.strip()][:2]
                errors.append(l + ("\n    " + " | ".join(ctxl) if ctxl else ""))
            elif "Reference `" in l and "undefined" in l:
                undefined.append(re.sub(r".*Reference `([^']*)'.*", r"\1", l))
            elif "multiply defined" in l or "multiply-defined" in l:
                multiply += 1
            elif l.startswith("Overfull \\hbox"):
                overfull += 1
    pdf = d / "build" / "main.pdf"
    print(f"latexmk: код {proc.returncode}, {secs:.0f} с; ошибок {len(errors)}, "
          f"undefined refs {len(undefined)}, multiply defined {multiply}, overfull {overfull}")
    for e in errors[:20]:
        print("  " + e)
    for u in sorted(set(undefined))[:20]:
        print("  undefined: " + u)
    if proc.returncode != 0 and not errors:
        tail = (proc.stdout + proc.stderr).strip().split("\n")[-15:]
        print("\n".join("  " + x for x in tail))
    if pdf.is_file():
        print(f"pdf: {pdf.relative_to(roam.VAULT)}")
        if open_pdf and sys.platform == "darwin":
            subprocess.run(["open", str(pdf)])
    return 1 if (proc.returncode != 0 or errors) else 0


