def _ind(text: str, n: int = 2) -> str:
    pad = " " * n
    return "\n".join(pad + l if l.strip() else "" for l in text.split("\n"))


def render_list(lb: ListBlock, ctx: Ctx) -> str:
    head = "\\begin{%s}" % lb.kind
    if lb.kind == "enumerate" and lb.first_number != 1:
        head += "[start=%d]" % lb.first_number
    out = [head]
    for it in lb.items:
        body = prose_to_tex(it.text, ctx, it.line)
        first, *rest = body.split("\n")
        out.append("  \\item " + first)
        for l in rest:
            out.append(_ind(l, 4) if l.strip() else "")
        for ch in it.children:
            out.append(_ind(render_list(ch, ctx), 4))
    out.append("\\end{%s}" % lb.kind)
    return "\n".join(out)


def render_table(t: Table, ctx: Ctx) -> str:
    width = max((len(r) for r in t.rows if r), default=1)
    out = ["\\begin{center}", "\\begin{tabular}{%s}" % " ".join(["l"] * width), "  \\hline"]
    for k, r in enumerate(t.rows):
        if r is None:
            out.append("  \\hline")
            continue
        cells = [prose_to_tex(c, ctx, t.line + k) for c in r] + [""] * (width - len(r))
        out.append("  " + " & ".join(cells) + " \\\\")
    out += ["  \\hline", "\\end{tabular}", "\\end{center}"]
    return "\n".join(out)


REM_TITLE_RE = re.compile(r"^\(([^()]+)\):\s*")


def _remark(b: Rem, ctx: Ctx) -> str:
    """/Rem/ → remark.  Ведущая скобка «(на лекции не было): …» -- заголовок замечания."""
    text, opt = b.text, ""
    m = REM_TITLE_RE.match(text)
    if m and text[m.end():].strip():
        opt = "[%s]" % prose_to_tex(m.group(1), ctx, b.line)
        rest = text[m.end():]
        text = rest[:1].upper() + rest[1:]
    return "\\begin{remark}%s\n%s\n\\end{remark}" % (opt, _ind(prose_to_tex(text, ctx, b.line)))


def render_blocks(blocks: list, ctx: Ctx, hoist: bool = False) -> tuple[str, list[str]]:
    """Return (body, hoisted_remarks).  With hoist=True the /Rem/ paragraphs
    are returned separately (as ready remark environments) instead of in place."""
    parts, rems = [], []
    for b in blocks:
        if isinstance(b, Para):
            body = prose_to_tex(b.text, ctx, b.line)
            if FIG_RE.match(b.text):
                body = "\\begin{center}\n%s\n\\end{center}" % _ind(body)
            parts.append(body)
        elif isinstance(b, Code):
            parts.append("\\begin{Verbatim}[fontsize=\\small]\n%s\n\\end{Verbatim}" % b.text)
        elif isinstance(b, Table):
            parts.append(render_table(b, ctx))
        elif isinstance(b, Rem):
            (rems if hoist else parts).append(_remark(b, ctx))
        elif isinstance(b, ListBlock):
            parts.append(render_list(b, ctx))
        elif isinstance(b, Quote):
            inner, r = render_blocks(b.blocks, ctx)
            rems += r
            parts.append("\\begin{quote}\n%s\n\\end{quote}" % _ind(inner))
    return "\n\n".join(parts), rems


def note_env(note: Note, ctx: Ctx) -> str:
    for t in note.tags:
        if t in ENV_BY_TYPE:
            return ENV_BY_TYPE[t]
    ctx.warn("X11", note.kw_line("filetags") + 1 if note.kw_line("filetags") is not None else 0,
             "нет тега типа -- выводится как «Утверждение»")
    return "proposition"


def _heading_title(h, ctx: Ctx) -> str:
    t = re.sub(r"[.:]\s*$", "", h.title.strip())
    return prose_to_tex(t, ctx, h.line)


def _render_region(lines: list[str], base: int, ctx: Ctx, hoist: bool = False) -> tuple[str, list[str]]:
    blocks = segment_ext(lines, base, ctx)
    return render_blocks(blocks, ctx, hoist=hoist)


def _render_steps(note: Note, h, ctx: Ctx, depth: int) -> str:
    """Body of a heading plus its sub-headings as \\proofpart / \\proofstep."""
    lines, base = _own_body(note, h)
    body, rems = _render_region(lines, base, ctx)
    parts = [body] if body.strip() else []
    parts += rems
    for c in _children(note, h):
        cmd = "\\proofpart" if depth == 0 else "\\proofstep"
        sub = _render_steps(note, c, ctx, depth + 1)
        parts.append("%s{%s}\n%s" % (cmd, _heading_title(c, ctx), sub) if sub.strip()
                     else "%s{%s}" % (cmd, _heading_title(c, ctx)))
    return "\n\n".join(parts)


def note_to_tex(note: Note, vault: Vault, exported: set[str]) -> tuple[str, list[TexWarning]]:
    ctx = Ctx(note, vault, exported)
    env = note_env(note, ctx)
    title = note.title
    if env == "theorem" and re.match(r"Теорема\s+[А-ЯЁ]", title):
        # «Теорема: Теорема Ферма» -> «Теорема: Ферма»
        title = re.sub(r"^Теорема\s+", "", title)
    title = prose_to_tex(title, ctx, note.kw_line("title") or 0)
    out = [f"{GENERATED}", f"% {note.rel} (body {note.body_hash()[:12]})", ""]

    top = [h for h in note.headings if h.parent is None]
    end = note.headings[0].line if note.headings else len(note.lines)
    body, rems = _render_region(note.lines[note.body_start:end], note.body_start, ctx, hoist=True)
    if body.strip():
        out.append("\\begin{%s}[{%s}]\\label[%s]{note:%s}" % (env, title, env, note.id))
        out.append(_ind(body))
        out.append("\\end{%s}" % env)
    else:
        ctx.warn("X06", note.body_start + 1, "пустая формулировка")
    for r in rems:
        out += ["", r]

    k = 0
    for h in top:
        if h.noexport():
            continue
        key, hnote = _heading_key(h.title)
        hnote = prose_to_tex(hnote, ctx, h.line) if hnote else ""
        kind = HEADING_ENV.get(key) or TEX_HEADING_KIND.get(re.split(r"[\s:]", key, maxsplit=1)[0])
        if kind == "proof":
            body = _render_steps(note, h, ctx, 0)
            if not body.strip():
                ctx.warn("X06", h.line + 1, "пустое доказательство")
                continue
            opt = "[Доказательство (%s)]" % hnote if hnote else ""
            out += ["", "\\begin{proof}%s" % opt, _ind(body), "\\end{proof}"]
        elif kind in ("example", "remark", "corollary"):
            body = _render_steps(note, h, ctx, 0)
            if not body.strip():
                ctx.warn("X06", h.line + 1, f"пустой раздел «{h.title}»")
                continue
            opt = "[%s]" % _heading_title(h, ctx) if kind == "remark" and key not in HEADING_ENV else ""
            opt = opt or ("[%s]" % hnote if hnote else "")
            out += ["", "\\begin{%s}%s" % (kind, opt), _ind(body), "\\end{%s}" % kind]
        elif kind != "proposition":
            ctx.warn("X01", h.line + 1, f"неизвестный заголовок «{h.title}» -- выводится как абзац без рамки")
            body = _render_steps(note, h, ctx, 0)
            if not body.strip():
                ctx.warn("X06", h.line + 1, f"пустой раздел «{h.title}»")
                continue
            out += ["", "\\paragraph*{%s}" % _heading_title(h, ctx), body]
        else:
            k += 1
            lines, base = _own_body(note, h)
            body, r2 = _render_region(lines, base, ctx, hoist=True)
            out.append("")
            out.append("\\begin{proposition}[{%s}]\\label[proposition]{note:%s:%d}"
                       % (_heading_title(h, ctx), note.id, k))
            proof_parts = []
            for c in _children(note, h):
                if HEADING_ENV.get(_heading_key(c.title)[0]) == "proof":
                    proof_parts.append(_render_steps(note, c, ctx, 0))
                else:
                    sub = _render_steps(note, c, ctx, 1)
                    body += "\n\n\\proofpart{%s}\n%s" % (_heading_title(c, ctx), sub)
            out.append(_ind(body))
            out.append("\\end{proposition}")
            for r in r2:
                out += ["", r]
            for p in proof_parts:
                if p.strip():
                    out += ["", "\\begin{proof}", _ind(p), "\\end{proof}"]
    return "\n".join(out).rstrip("\n") + "\n", ctx.warnings


