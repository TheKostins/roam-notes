def print_plan(c: Course, vault: Vault) -> None:
    print(f"{c.title} -- {c.subtitle}")
    print(f"глав {len(c.lectures)}, заметок {len(c.exported)}, приложение "
          f"{sum(len(i) for _, i in c.appendix)}")
    for plan in c.lectures:
        print(f"\nГлава {plan.number}. {plan.title}  ({plan.note.rel}, {plan.date or '-'})")
        for si, s in enumerate(plan.sections, 1):
            if s.title:
                print(f"  {plan.number}.{si} {s.title}" + (f"  [конспект {s.ref}]" if s.ref else ""))
            for it in s.items:
                n = vault.by_id[it.id]
                env = next((ENV_BY_TYPE[t] for t in n.tags if t in ENV_BY_TYPE), "proposition")
                print(f"      {env:<12} {n.title}" + (f"  -- {it.annot}" if it.annot else ""))
    if c.appendix:
        print("\nПриложение. Вспомогательные утверждения")
        for plan, items in c.appendix:
            print(f"  К лекции {plan.number}")
            for it in items:
                n = vault.by_id[it.id]
                env = next((ENV_BY_TYPE[t] for t in n.tags if t in ENV_BY_TYPE), "proposition")
                print(f"      {env:<12} {n.title}" + (f"  -- {it.annot}" if it.annot else ""))


def print_warnings(warnings: list[TexWarning]) -> None:
    if not warnings:
        print("\nпредупреждений нет")
        return
    by: dict[str, list[TexWarning]] = {}
    for w in warnings:
        by.setdefault(w.note, []).append(w)
    print(f"\nпредупреждения: {len(warnings)}")
    for note, ws in by.items():
        print(f"  {note}")
        for w in sorted(ws, key=lambda w: (w.line, w.code)):
            print("    " + w.fmt())


def warnings_json(warnings: list[TexWarning]) -> list[dict]:
    return [{"id": w.note_id, "note": w.note, "line": w.line, "code": w.code, "message": w.message}
            for w in warnings]
