def macros_source_raw(cfg: dict) -> list[str]:
    """Strings of my/notes-latex-macros in source order (LaTeX as-is)."""
    p = Path(cfg["vault"].get("emacs_macros", "")).expanduser()
    if not p.is_file():
        return []
    src = p.read_text(encoding="utf-8")
    start = src.find("(defvar my/notes-latex-macros")
    if start < 0:
        return []
    nxt = re.search(r"^\((defun|defvar|defmacro|use-package)\b", src[start + 10:], re.M)
    region = src[start: start + 10 + nxt.start()] if nxt else src[start:]
    region = "\n".join(re.sub(r"^\s*;.*$", "", l) for l in region.split("\n"))
    out = []
    for m in re.finditer(r'"((?:[^"\\]|\\.)*)"', region, re.S):
        s = roam.elisp_unescape(m.group(1)).strip()
        if s.startswith("\\"):
            out.append(s)
    return out


def macros_latex(cfg: dict) -> str:
    lines = macros_source_raw(cfg)
    head = [GENERATED, f"% источник: my/notes-latex-macros ({cfg['vault'].get('emacs_macros', '')})", ""]
    return "\n".join(head + lines) + "\n"


