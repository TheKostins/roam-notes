def print_warnings(warnings: list[TexWarning]) -> None:
    if not warnings:
        print("\nпредупреждений нет")
        return
    by: dict[str, list[TexWarning]] = {}
    for w in warnings:
        by.setdefault(w.note, []).append(w)
    print(f"\nпредупреждения: {len(warnings)}")
    for note, ws in by.items():
        print(f"  {note}")
        for w in sorted(ws, key=lambda w: (w.line, w.code)):
            print("    " + w.fmt())


def warnings_json(warnings: list[TexWarning]) -> list[dict]:
    return [{"id": w.note_id, "note": w.note, "line": w.line, "code": w.code, "message": w.message}
            for w in warnings]
