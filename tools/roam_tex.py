def write_files(files: dict[str, str], course: str, dry_run: bool = False) -> dict[str, list[str]]:
    root = handbook_root()
    summary = {"created": [], "updated": [], "deleted": [], "unchanged": []}
    for rel, content in files.items():
        p = root / rel
        if p.exists():
            if p.read_text(encoding="utf-8") == content:
                summary["unchanged"].append(rel)
                continue
            summary["updated"].append(rel)
        else:
            summary["created"].append(rel)
        if not dry_run:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(content, encoding="utf-8")
    for sub in ("notes", "chapters"):
        d = root / course / sub
        if not d.is_dir():
            continue
        for p in sorted(d.glob("*.tex")):
            rel = f"{course}/{sub}/{p.name}"
            if rel in files:
                continue
            head = p.read_text(encoding="utf-8").split("\n", 1)[0]
            if head.startswith("% generated by roam.py"):
                summary["deleted"].append(rel)
                if not dry_run:
                    p.unlink()
    main = root / course / "main.tex"
    if not main.exists():
        summary["created"].append(f"{course}/main.tex")
        if not dry_run:
            main.parent.mkdir(parents=True, exist_ok=True)
            main.write_text(MAIN_TEX, encoding="utf-8")
            (root / course / "text").mkdir(exist_ok=True)
            (root / course / "text" / ".keep").touch()
    return summary


