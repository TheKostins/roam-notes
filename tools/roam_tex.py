def handbook_root() -> Path:
    return roam.VAULT / "handbook"


def course_plan(vault: Vault, course: str) -> Course:
    """План курса с ручными настройками из handbook/<курс>/handbook.toml."""
    local: dict = {}
    p = handbook_root() / course / "handbook.toml"
    if p.is_file():
        local = tomllib.loads(p.read_text(encoding="utf-8"))
    return roam_doc.course_plan(vault, course, local)


def _tex_str(s: str) -> str:
    return re.sub(r"(?<!\\)([%&#_~^$])", lambda m: _ESC[m.group(1)], s)


def render_course(vault: Vault, course: str) -> tuple[Course, dict[str, str], list[TexWarning]]:
    """Return (course, {relpath under handbook/: content}, warnings)."""
    c = course_plan(vault, course)
    warnings = list(c.warnings)
    files: dict[str, str] = {}
    macros = macros_latex(vault.cfg)
    files["common/macros.tex"] = macros

    for nid in sorted(c.exported):
        tex, w = note_to_tex(vault.by_id[nid], vault, c.exported)
        warnings += w
        files[f"{course}/notes/{nid}.tex"] = tex

    chapters = []
    emitted: set[str] = set()
    for plan in c.lectures:
        if not plan.sections:
            continue                     # X10 уже выдан: глава без плана не выводится
        nn = "%02d" % plan.number
        out = [GENERATED, f"% {plan.note.rel}", "",
               "\\chapter{%s}\\label{lecture:%d}" % (_tex_str(plan.title), plan.number),
               "\\InputIfFileExists{text/%s-intro}{}{}" % nn]
        for si, s in enumerate(plan.sections, 1):
            if s.title:
                out += ["", "\\section{%s}\\label{lecture:%d:%d}%s"
                        % (_tex_str(s.title), plan.number, si, f"  % конспект {s.ref}" if s.ref else ""),
                        "\\InputIfFileExists{text/%s-%d-intro}{}{}" % (nn, si)]
            for it in s.items:
                if it.id in emitted:     # повтор: ссылка вместо второго экземпляра
                    out += ["", "\\noteagain{%s}{%s}  %% %s" % (it.id, _tex_str(vault.by_id[it.id].title),
                                                               f"-- {it.annot}" if it.annot else "повтор")]
                    continue
                emitted.add(it.id)
                out += ["", "\\InputIfFileExists{text/%s-before}{}{}" % it.id,
                        "\\input{notes/%s}  %% %s%s" % (it.id, vault.by_id[it.id].title,
                                                       f" -- {it.annot}" if it.annot else "")]
        out += ["", "\\InputIfFileExists{text/%s-outro}{}{}" % nn, ""]
        files[f"{course}/chapters/{nn}.tex"] = "\n".join(out)
        chapters.append(nn)
    files[f"{course}/chapters.tex"] = "\n".join([GENERATED, ""] + ["\\input{chapters/%s}" % nn for nn in chapters] + [""])

    out = [GENERATED, "", "\\chapter{Вспомогательные утверждения}\\label{aux}",
           "\\InputIfFileExists{text/aux-intro}{}{}"]
    for plan, items in c.appendix:
        out += ["", "\\section{К лекции %d}\\label{aux:%d}" % (plan.number, plan.number)]
        for it in items:
            out += ["", "\\InputIfFileExists{text/%s-before}{}{}" % it.id,
                    "\\input{notes/%s}  %% %s%s" % (it.id, vault.by_id[it.id].title,
                                                   f" -- {it.annot}" if it.annot else "")]
    out.append("")
    files[f"{course}/aux.tex"] = "\n".join(out)

    files[f"{course}/meta.tex"] = "\n".join([
        GENERATED, "",
        "\\newcommand{\\handbooktitle}{%s}" % _tex_str(c.title),
        "\\newcommand{\\handbooksubtitle}{%s}" % _tex_str(c.subtitle),
        "\\newcommand{\\handbookcount}{%d}" % len(c.exported),
        "\\newcommand{\\handbooklectures}{%d}" % len(chapters), ""])
    return c, files, warnings


