def _protect(text: str, ctx: Ctx, line0: int) -> tuple[str, list]:
    frags, problems = scan_math(text)
    for rule, off, msg in problems:
        ctx.warn("X02", line0 + text.count("\n", 0, off) + 1, f"математика: {msg}")
    masked = blank_ranges(text, frags)
    spans = [(f.start, f.end, "math", f.kind) for f in frags]
    spans += [(m.start(), m.end(), "link", None) for m in LINK_RE.finditer(masked)]
    spans.sort()
    out, tokens, pos = [], [], 0
    for s, e, kind, sub in spans:
        if s < pos:
            continue
        out.append(text[pos:s])
        idx = len(tokens)
        tokens.append((kind, sub, text[s:e], line0 + text.count("\n", 0, s) + 1))
        disp = kind == "math" and sub in ("display", "env", "ddollar")
        out.append(("\uE002" if disp else "\uE000") + str(idx) + "\uE001")
        pos = e
    out.append(text[pos:])
    return "".join(out), tokens


_EMPH_RE = re.compile(r"(?<![\w/\\])/(?=[^\s)\]])([^/\n\uE002]*?[^\s(\[])/(?![\w/])")
_BOLD_RE = re.compile(r"(?<![\w*\\])\*(?=[^\s)\]])([^*\n\uE002]*?[^\s(\[])\*(?![\w*])")
_DASH_RE = re.compile(r"(?<=\S)[ \t](?:--|—)(?=[ \t\n]|$)")


def _render_link(raw: str, ctx: Ctx, line: int) -> str:
    m = LINK_RE.match(raw)
    target, desc = m.group(1).strip(), m.group(2)
    low = target.lower()
    if low.startswith("id:"):
        nid = target[3:].strip().upper()
        tgt = ctx.vault.by_id.get(nid)
        if desc is None:
            desc = tgt.title if tgt else target
        text = prose_to_tex(desc, ctx, line)
        if nid in ctx.exported:
            return "\\hyperref[note:%s]{%s}" % (nid, text)
        if tgt is None:
            ctx.warn("X03", line, f"битая ссылка id:{nid[:8]}")
        else:
            ctx.warn("X07", line, f"ссылка на неэкспортируемую заметку «{tgt.title}» -- выводится текстом")
        return text
    ctx.warn("X04", line, f"внешняя ссылка {target[:50]}")
    if desc:
        return prose_to_tex(desc, ctx, line)
    return "\\url{%s}" % target


_BREAK_END = tuple(".,;:!?(") + ("---", "\\\\")
_UPPER_RE = re.compile(r"[А-ЯЁA-Z]")


def _sentence_breaks(s: str) -> str:
    """Notes often end a phrase at a line end without a period and start the
    next phrase with a capital letter; joined into one paragraph this reads as
    «...формулу Итого».  Keep such a break visible with `\\\\`.
    Runs on protected text: math/links are tokens, a display is \uE002n\uE001."""
    lines = s.split("\n")
    for k in range(len(lines) - 1):
        prev, nxt = lines[k].rstrip(), lines[k + 1].lstrip()
        if (prev and nxt and not prev.endswith(_BREAK_END)
                and not re.search("\uE002\\d+\uE001$", prev)
                and _UPPER_RE.match(nxt)):
            lines[k] = prev + " \\\\"
    return "\n".join(lines)


def prose_to_tex(text: str, ctx: Ctx, line0: int = 0) -> str:
    """Convert a prose span (paragraph, list item, heading title) to LaTeX.
    Math and links are protected first, so nothing below can touch them."""
    s, tokens = _protect(text, ctx, line0)
    s = re.sub(r"(?<!\\)([%&#_~^$])", lambda m: _ESC[m.group(1)], s)
    s = _EMPH_RE.sub(lambda m: "\\emph{%s}" % m.group(1), s)
    s = _BOLD_RE.sub(lambda m: "\\textbf{%s}" % m.group(1), s)

    def dash(m: re.Match) -> str:
        before = s[:m.start()]
        t = re.search("\uE002(\\d+)\uE001$", before)
        return " ---" if t else "~---"
    s = _DASH_RE.sub(dash, s)

    def uni(m: re.Match) -> str:
        ch = m.group(0)
        ctx.warn("X05", line0 + s.count("\n", 0, m.start()) + 1,
                 f"символ «{ch}» в прозе выведен как формула")
        return "$%s$" % UNICODE_MATH[ch]
    s = re.sub("[%s]" % re.escape("".join(UNICODE_MATH)), uni, s)
    s = _sentence_breaks(s)

    def restore(m: re.Match) -> str:
        kind, sub, raw, line = tokens[int(m.group(1))]
        if kind == "math":
            return raw
        return _render_link(raw, ctx, line)
    return TOK_RE.sub(restore, s)


