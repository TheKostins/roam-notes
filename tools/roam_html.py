segment_html = segment_ext   # Code / Table теперь в roam_doc


FIG_RE = re.compile(r"^\s*\[\[file:[^\]]+\](?:\[[^\]]*\])?\]\s*$")


def render_list(lb: ListBlock, ctx: HCtx) -> str:
    tag = "ol" if lb.kind == "enumerate" else "ul"
    head = f'<{tag} start="{lb.first_number}">' if tag == "ol" and lb.first_number != 1 else f"<{tag}>"
    out = [head]
    for it in lb.items:
        body = prose_to_html(it.text, ctx, it.line)
        for ch in it.children:
            body += "\n" + render_list(ch, ctx)
        out.append(f"<li>{body}</li>")
    out.append(f"</{tag}>")
    return "\n".join(out)


def render_table(t: Table, ctx: HCtx) -> str:
    out = ["<table>"]
    header = t.rows and t.rows[0] is not None and len(t.rows) > 1 and t.rows[1] is None
    for k, r in enumerate(t.rows):
        if r is None:
            continue
        cell = "th" if header and k == 0 else "td"
        out.append("<tr>" + "".join(f"<{cell}>{prose_to_html(c, ctx, t.line + k)}</{cell}>" for c in r) + "</tr>")
    out.append("</table>")
    return "\n".join(out)


def render_blocks(blocks: list, ctx: HCtx) -> str:
    parts = []
    for b in blocks:
        if isinstance(b, Para):
            body = prose_to_html(b.text, ctx, b.line)
            if FIG_RE.match(b.text):
                parts.append(f'<figure>{body}</figure>')
            else:
                parts.append(f"<p>{body}</p>")
        elif isinstance(b, Rem):
            parts.append('<aside class="rem">\n<p>%s</p>\n</aside>' % prose_to_html(b.text, ctx, b.line))
        elif isinstance(b, ListBlock):
            parts.append(render_list(b, ctx))
        elif isinstance(b, Quote):
            parts.append("<blockquote>\n%s\n</blockquote>" % render_blocks(b.blocks, ctx))
        elif isinstance(b, Code):
            lang = f' class="lang-{attr(b.lang)}"' if b.lang else ""
            parts.append(f"<pre><code{lang}>{esc(b.text)}</code></pre>")
        elif isinstance(b, Table):
            parts.append(render_table(b, ctx))
    return "\n".join(parts)


def render_region(lines: list[str], base: int, ctx: HCtx) -> str:
    return render_blocks(segment_html(lines, base, ctx), ctx)


def heading_title(h, ctx: HCtx) -> str:
    return prose_to_html(re.sub(r"[.:]\s*$", "", h.title.strip()), ctx, h.line)


def heading_kind(h) -> str | None:
    return HEADING_KIND.get(heading_key(h.title)[0])


def render_steps(note: Note, h, ctx: HCtx, level: int) -> str:
    """Тело заголовка и его подзаголовки как <h3>/<h4>…"""
    lines, base = own_body(note, h)
    parts = [render_region(lines, base, ctx)]
    for c in children(note, h):
        tag = f"h{min(level, 6)}"
        parts.append(f"<{tag}>{heading_title(c, ctx)}</{tag}>")
        parts.append(render_steps(note, c, ctx, level + 1))
    return "\n".join(p for p in parts if p.strip())


