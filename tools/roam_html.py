def esc(s: str) -> str:
    return html.escape(s, quote=False)


def attr(s: str) -> str:
    return html.escape(s, quote=True)


def fmt_date(s: str | None) -> str:
    """'20261004181419' or '2026-10-04' → '4 окт 2026'."""
    if not s:
        return ""
    d = re.sub(r"\D", "", s)[:8]
    if len(d) < 8:
        return s
    try:
        return f"{int(d[6:8])} {MONTHS[int(d[4:6]) - 1]} {d[:4]}"
    except (ValueError, IndexError):
        return s


