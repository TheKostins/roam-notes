def aside_html(page: Page | None, site: Site, toc: list[tuple[str, str]], root: str) -> str:
    out = []
    if toc:
        out.append('<section class="toc"><h3>Оглавление</h3><ul>%s</ul></section>'
                   % "".join(f'<li><a href="#{a}">{esc(t)}</a></li>' for a, t in toc))
    if page is not None:
        out.append('<section><h3>Локальный граф</h3><div class="graph"><canvas data-graph="local"></canvas>'
                   f'<a class="expand" href="{root}graph/?id={page.id}" aria-label="Весь граф">'
                   '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round"><path d="M15 3h6v6M9 21H3v-6M21 3l-7 7M3 21l7-7"/></svg></a></div>'
                   + LEGEND + "</section>")
        out.append('<section class="backlinks"><h3>Сюда ссылаются</h3>%s</section>' % backlinks_html(page, site, root))
    return "\n".join(out)


def lecture_label(plan: Plan) -> str:
    if plan.number is None:
        return plan.title
    if plan.title == plan.note.title or not plan.title:
        return f"Лекция {plan.number}"
    return f"Лекция {plan.number}: {plan.title}"


def _page_kind(p: Page) -> str:
    if p.stub:
        return "stub"
    if "lecture" in p.note.tags:
        return "lecture"
    return p.type or "other"


def explorer_html(site: Site) -> str:
    """Проводник: курс → лекции (план) → заметки; '@@ROOT@@' заменяется на
    относительный корень при вставке в страницу."""
    R = "@@ROOT@@"

    def item(p: Page) -> str:
        cls = ' class="stub"' if p.stub else ""
        return f'<li><a{cls} href="{R}{p.url}" data-id="{p.id}"><i class="ty ty-{_page_kind(p)}"></i>{esc(p.title)}</a></li>'

    out = []
    for course in site.courses:
        out.append(f'<div class="nav-h"><a href="{R}{course}/">{esc(site.course_name(course))}</a></div><ul>')
        for plan in site.plans.get(course, []):
            lp = site.pages[plan.note.id]
            items = [item(site.pages[i.id]) for s in plan.sections for i in s.items]
            label = lecture_label(plan)
            out.append(f'<li><details><summary><a href="{R}{lp.url}" data-id="{lp.id}">{esc(label)}</a></summary><ul>'
                       + "".join(items) + "</ul></details></li>")
        rest = site.off_plan(course)
        if rest:
            label = "Вне плана" if site.plans.get(course) else "Заметки"
            out.append(f'<li><details><summary>{label}</summary><ul>' + "".join(item(p) for p in rest) + "</ul></details></li>")
        out.append("</ul>")
    out.append(f'<div class="nav-h">Ещё</div><ul><li><a href="{R}graph/">⌘ Граф всех заметок</a></li>'
               f'<li><a href="{R}tags/"># Теги</a></li></ul>')
    return "\n".join(out)


def course_page(course: str, site: Site, root: str) -> tuple[str, list[tuple[str, str]]]:
    out = [f"<h1>{esc(site.course_name(course))}</h1>"]
    toc = []
    plans = site.plans.get(course, [])
    n_notes = sum(1 for p in site.pages.values() if p.course == course and "lecture" not in p.note.tags and not p.stub)
    out.append(f'<div class="meta"><span>заметок: {n_notes}</span><span>·</span><span>лекций: {len(plans)}</span></div>')
    for k, plan in enumerate(plans, 1):
        lp = site.pages[plan.note.id]
        label = lecture_label(plan)
        lctx = HCtx(plan.note, site.v, set(site.pages), site=site, root=root)
        out.append(f'<section class="sec" id="l{k}"><h2><a href="{root}{lp.url}">{esc(label)}</a>'
                   f'{"<small>" + fmt_date(plan.date) + "</small>" if plan.date else ""}</h2>')
        toc.append((f"l{k}", label))
        for s in plan.sections:
            if s.title:
                out.append(f"<h3>{esc(s.title)}</h3>")
            out.append("<ul class=\"plan\">")
            for i in s.items:
                p = site.pages[i.id]
                annot = f" <span class=\"annot\">{prose_to_html(i.annot, lctx, i.line)}</span>" if i.annot else ""
                cls = ' class="stub"' if p.stub else ""
                out.append(f'<li><i class="ty ty-{_page_kind(p)}"></i><a{cls} href="{root}{p.url}">{esc(p.title)}</a>{annot}</li>')
            out.append("</ul>")
        if plan.appendix:
            out.append('<h3>Вне конспекта</h3><ul class="plan">')
            for i in plan.appendix:
                p = site.pages[i.id]
                out.append(f'<li><i class="ty ty-{_page_kind(p)}"></i><a href="{root}{p.url}">{esc(p.title)}</a></li>')
            out.append("</ul>")
        out.append("</section>")
    rest = site.off_plan(course)
    if rest:
        out.append('<section class="sec" id="rest"><h2>%s</h2><ul class="plan">' % ("Вне плана" if plans else "Заметки"))
        toc.append(("rest", "Вне плана" if plans else "Заметки"))
        for p in rest:
            cls = ' class="stub"' if p.stub else ""
            out.append(f'<li><i class="ty ty-{_page_kind(p)}"></i><a{cls} href="{root}{p.url}">{esc(p.title)}</a></li>')
        out.append("</ul></section>")
    return "\n".join(out), toc


def home_page(site: Site) -> str:
    out = [f"<h1>{esc(site.cfg['title'])}</h1>"]
    if site.cfg["intro"]:
        out.append(f"<p class=\"intro\">{esc(site.cfg['intro'])}</p>")
    out.append('<div class="cards">')
    for course in site.courses:
        n = sum(1 for p in site.pages.values() if p.course == course and "lecture" not in p.note.tags and not p.stub)
        out.append(f'<a class="card" href="{course}/"><b>{esc(site.course_name(course))}</b>'
                   f'<span>{n} заметок · {len(site.plans.get(course, []))} лекций</span></a>')
    out.append("</div>")
    recent = sorted((p for p in site.pages.values() if not p.stub), key=lambda p: p.note.path.stat().st_mtime, reverse=True)[:12]
    out.append('<section class="sec"><h2>Недавно изменённые</h2><ul class="plan">')
    for p in recent:
        when = fmt_date(dt.datetime.fromtimestamp(p.note.path.stat().st_mtime).strftime("%Y%m%d"))
        out.append(f'<li><i class="ty ty-{_page_kind(p)}"></i><a href="{p.url}">{esc(p.title)}</a> <span class="annot">{when}</span></li>')
    out.append("</ul></section>")
    return "\n".join(out)


def tags_index(site: Site) -> tuple[str, dict[str, list[Page]]]:
    by_tag: dict[str, list[Page]] = {}
    for p in site.pages.values():
        for t in p.note.tags:
            if t in WORKFLOW_HIDE or t in ("backfill", "review"):
                continue
            by_tag.setdefault(t, []).append(p)
    out = ["<h1>Теги</h1>", '<ul class="plan tags">']
    for t in sorted(by_tag, key=lambda t: (t not in site.v.courses, t not in TYPE_LABEL, t)):
        out.append(f'<li><a class="tag" href="{t}/">{esc(t)}</a> <span class="annot">{len(by_tag[t])}</span></li>')
    out.append("</ul>")
    return "\n".join(out), by_tag


def tag_page(tag: str, pages: list[Page], root: str) -> str:
    out = [f"<h1>#{esc(tag)}</h1>", '<ul class="plan">']
    for p in sorted(pages, key=lambda p: p.title.casefold()):
        cls = ' class="stub"' if p.stub else ""
        out.append(f'<li><i class="ty ty-{_page_kind(p)}"></i><a{cls} href="{root}{p.url}">{esc(p.title)}</a></li>')
    out.append("</ul>")
    return "\n".join(out)


