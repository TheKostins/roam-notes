def fill(tpl: str, **vals: str) -> str:
    return re.sub(r"\{\{(\w+)\}\}", lambda m: vals.get(m.group(1), ""), tpl)


def render_site(site: Site) -> tuple[dict[str, str | bytes], list[DocWarning]]:
    tpl = (ASSETS / "template.html").read_text(encoding="utf-8")
    explorer = explorer_html(site)
    macros = json.dumps(site.mathjax_macros(), ensure_ascii=False)
    base = site.cfg["base_url"].rstrip("/") + "/" if site.cfg["base_url"] else ""
    warnings = list(site.warnings)
    files: dict[str, str | bytes] = {}

    def page(path: str, title: str, article: str, aside: str, root: str, nid: str = "", desc: str = "") -> None:
        files[path] = GENERATED + "\n" + fill(
            tpl, title=esc(title), site_title=esc(site.cfg["title"]), site_author=esc(site.cfg["author"]),
            description=attr(desc), canonical=attr(base + path.removesuffix("index.html")) if base else "",
            mathjax_macros=macros, root=root, id=nid, article=article, aside=aside,
            explorer=explorer.replace("@@ROOT@@", root))

    for p in site.pages.values():
        article, toc, w = note_article(p, site)
        warnings += w
        root = "../" * p.depth
        desc = re.sub(r"\s+", " ", " ".join(p.note.statement_lines(cap=3)))[:200]
        page(p.url + "index.html", p.title, article, aside_html(p, site, toc, root), root, p.id, desc)
    for course in site.courses:
        article, toc = course_page(course, site, "../")
        page(f"{course}/index.html", site.course_name(course), article, aside_html(None, site, toc, "../"), "../")
    page("index.html", site.cfg["title"], home_page(site), "", "")
    page("graph/index.html", "Граф", graph_page(), "", "../")
    tags_html, by_tag = tags_index(site)
    page("tags/index.html", "Теги", tags_html, "", "../")
    for t, ps in by_tag.items():
        page(f"tags/{t}/index.html", f"#{t}", tag_page(t, ps, "../../"), "", "../../")

    files["graph.json"] = json.dumps(graph_json(site), ensure_ascii=False, separators=(",", ":"))
    files["search.json"] = json.dumps(search_json(site), ensure_ascii=False, separators=(",", ":"))
    files["id-map.json"] = json.dumps({p.id: p.url for p in site.pages.values()}, ensure_ascii=False, separators=(",", ":"))
    for name in ("site.css", "site.js"):
        files[name] = (ASSETS / name).read_text(encoding="utf-8")
    for rel in sorted(site.images):
        src = roam.VAULT / rel
        if src.is_file():
            files[rel] = src.read_bytes()
    files[".nojekyll"] = ""
    return files, dedupe(warnings)


def dedupe(ws: list[DocWarning]) -> list[DocWarning]:
    out, seen = [], set()
    for w in ws:
        key = (w.note_id, w.line, w.code, w.message)
        if key not in seen:
            seen.add(key)
            out.append(w)
    return out


def write_site(files: dict[str, str | bytes], out: Path, dry_run: bool = False) -> dict[str, list[str]]:
    """Записать сайт в out/, удалив устаревшие файлы (каталог целиком управляется генератором)."""
    summary: dict[str, list[str]] = {"created": [], "updated": [], "deleted": [], "unchanged": []}
    existing = {str(p.relative_to(out)) for p in out.rglob("*") if p.is_file()} if out.is_dir() else set()
    for rel, content in files.items():
        p = out / rel
        data = content.encode("utf-8") if isinstance(content, str) else content
        if rel in existing:
            if p.read_bytes() == data:
                summary["unchanged"].append(rel)
                continue
            summary["updated"].append(rel)
        else:
            summary["created"].append(rel)
        if not dry_run:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_bytes(data)
    for rel in sorted(existing - set(files)):
        summary["deleted"].append(rel)
        if not dry_run:
            (out / rel).unlink()
    if not dry_run:
        for d in sorted((p for p in out.rglob("*") if p.is_dir()), key=lambda p: -len(p.parts)):
            if not any(d.iterdir()):
                d.rmdir()
    return summary


def print_plan(site: Site) -> None:
    print(f"{site.cfg['title']}: страниц {len(site.pages)}, курсов {len(site.courses)}")
    for course in site.courses:
        print(f"\n{site.course_name(course)} ({course})")
        for plan in site.plans.get(course, []):
            print(f"  Лекция {plan.number}: {plan.title}  [{plan.date or '--'}]")
            for s in plan.sections:
                if s.title:
                    print(f"    · {s.title}")
                for i in s.items:
                    p = site.pages[i.id]
                    print(f"      {'~' if p.stub else '-'} {p.title}  → {p.url}")
        rest = site.off_plan(course)
        if rest:
            print("  Вне плана" if site.plans.get(course) else "  Заметки")
            for p in rest:
                print(f"      {'~' if p.stub else '-'} {p.title}  → {p.url}")


def print_warnings(ws: list[DocWarning]) -> None:
    if not ws:
        return
    print(f"\nпредупреждений: {len(ws)}")
    cur = None
    for w in sorted(ws, key=lambda w: (w.note, w.line, w.code)):
        if w.note != cur:
            cur = w.note
            print(f"  {cur}")
        print("    " + w.fmt())
