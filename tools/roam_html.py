def math_html(raw: str, kind: str) -> str:
    if kind == "inline":
        raw = "\\(" + raw[1:-1] + "\\)"
    elif kind == "ddollar":
        raw = "\\[" + raw[2:-2] + "\\]"
    return esc(raw)


def _img(target: str, ctx: HCtx, line: int, desc: str | None) -> str:
    rel = target[len("file:"):].strip()
    src = (ctx.note.path.parent / rel)
    if not src.is_file():
        ctx.warn("X03", line, f"нет файла {rel}")
        return esc(desc or rel)
    if ctx.site is not None:
        ctx.site.images.add(rel)
    alt = attr(desc or Path(rel).stem)
    return f'<img src="{ctx.root}{attr(rel)}" alt="{alt}" loading="lazy">'


def render_link(raw: str, ctx: HCtx, line: int) -> str:
    m = LINK_RE.match(raw)
    target, desc = m.group(1).strip(), m.group(2)
    low = target.lower()
    if low.startswith("id:"):
        nid = target[3:].strip().upper()
        tgt = ctx.vault.by_id.get(nid)
        if desc is None:
            desc = tgt.title if tgt else target
        text = prose_to_html(desc, ctx, line)
        page = ctx.site.pages.get(nid) if ctx.site else None
        if page is not None:
            cls = "id stub" if page.stub else "id"
            return f'<a class="{cls}" href="{ctx.root}{page.url}">{text}</a>'
        if tgt is None:
            ctx.warn("X03", line, f"битая ссылка id:{nid[:8]}")
        else:
            ctx.warn("X07", line, f"ссылка на неопубликованную заметку «{tgt.title}» -- выводится текстом")
        return f'<span class="id missing">{text}</span>'
    if low.startswith("file:"):
        if Path(target).suffix.lower() in IMG_EXT:
            return _img(target, ctx, line, desc)
        ctx.warn("X04", line, f"ссылка на файл {target[:50]} -- выводится текстом")
        return prose_to_html(desc, ctx, line) if desc else esc(target)
    if low.startswith(("http:", "https:")):
        text = prose_to_html(desc, ctx, line) if desc else esc(target)
        return f'<a class="ext" href="{attr(target)}" target="_blank" rel="noopener">{text}</a>'
    ctx.warn("X04", line, f"внешняя ссылка {target[:50]}")
    return prose_to_html(desc, ctx, line) if desc else esc(target)


def prose_to_html(text: str, ctx: HCtx, line0: int = 0) -> str:
    """Проза → HTML: математика и ссылки защищены токенами, потом экранирование,
    разметка org (/курсив/, *жирный*, =код=, ~код~), тире, переносы фраз."""
    s, tokens = protect(text, ctx, line0)
    s = esc(s)
    s = EMPH_RE.sub(lambda m: "<em>%s</em>" % m.group(1), s)
    s = BOLD_RE.sub(lambda m: "<strong>%s</strong>" % m.group(1), s)
    s = CODE_RE.sub(lambda m: "<code>%s</code>" % m.group(2), s)
    s = DASH_RE.sub(" —", s)
    s = sentence_breaks(s, "<br>")

    def restore(m: re.Match) -> str:
        kind, sub, raw, line = tokens[int(m.group(1))]
        if kind == "math":
            return math_html(raw, sub)
        return render_link(raw, ctx, line)
    return TOK_RE.sub(restore, s)


