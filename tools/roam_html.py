def graph_json(site: Site) -> dict:
    nodes, links = [], []
    for p in site.pages.values():
        nodes.append({"id": p.id, "t": p.title, "u": p.url, "k": _page_kind(p), "c": p.course})
    seen = set()
    for p in site.pages.values():
        for oid in p.note.out_ids():
            if oid in site.pages and oid != p.id and (p.id, oid) not in seen:
                seen.add((p.id, oid))
                links.append([p.id, oid])
    return {"nodes": nodes, "links": links}


def search_json(site: Site) -> list[dict]:
    out = []
    for p in site.pages.values():
        text = "\n".join(p.note.content_lines("desc"))
        frags, _ = scan_math(text)
        text = blank_ranges(text, frags)
        text = re.sub(r"^\*+\s+", "", text, flags=re.M)
        text = re.sub(r"[/*=~_]{1}(?=\S)|(?<=\S)[/*=~_]{1}", " ", text)
        text = re.sub(r"\s+", " ", text).strip()[:3000]
        out.append({"id": p.id, "t": p.title, "u": p.url, "k": _page_kind(p), "c": p.course,
                    "g": [t for t in p.note.tags if t not in WORKFLOW_HIDE], "x": text})
    return out


