def note_article(page: Page, site: Site) -> tuple[str, list[tuple[str, str]], list[DocWarning]]:
    """(HTML статьи без оглавления/графа, пункты оглавления, предупреждения)."""
    note = page.note
    ctx = HCtx(note, site.v, set(site.pages), site=site, root="../" * page.depth)
    root = ctx.root
    toc: list[tuple[str, str]] = []
    out: list[str] = []

    crumbs = [f'<a href="{root}{page.course}/">{esc(site.course_name(page.course))}</a>']
    if page.lecture is not None and page.lecture.note.id != note.id:
        lp = site.pages[page.lecture.note.id]
        crumbs.append(f'<a href="{root}{lp.url}">Лекция {page.lecture.number}</a>')
    out.append('<div class="crumbs">%s</div>' % "<span>/</span>".join(crumbs))
    out.append(f"<h1>{prose_to_html(note.title, ctx, note.kw_line('title') or 0)}</h1>")

    meta = []
    if page.type:
        meta.append(f'<a class="tag type {page.type}" href="{root}tags/{page.type}/">{page.type}</a>')
    for t in note.tags:
        if t in site.v.courses or (t not in TYPE_LABEL and t not in site.v.workflow_tags):
            meta.append(f'<a class="tag" href="{root}tags/{attr(t)}/">{esc(t)}</a>')
    if page.stub:
        meta.append('<span class="tag stub">заглушка</span>')
    if note.created:
        meta.append(f"<span>·</span><span>{fmt_date(note.date or note.created)}</span>")
    if page.lecture is not None and page.lecture.note.id != note.id:
        lp = site.pages[page.lecture.note.id]
        meta.append(f'<span>·</span><a href="{root}{lp.url}">лекция {page.lecture.number}</a>')
    if site.cfg["show_status"]:
        st = site.v.status(note)
        meta.append(f'<span>·</span><span class="status {st}">{ {"audited": "проверено", "pending": "не проверено", "stub": "заглушка"}[st] }</span>')
    out.append('<div class="meta">%s</div>' % "\n".join(meta))

    if page.stub:
        out.append('<p class="stub-note">Заметка ещё не написана: на неё уже ссылаются, текст появится позже.</p>')
        return "\n".join(out), toc, ctx.warnings

    top = [h for h in note.headings if h.parent is None]
    end = note.headings[0].line if note.headings else len(note.lines)
    body = render_region(note.lines[note.body_start:end], note.body_start, ctx)
    if body.strip():
        if page.type in BOXED:
            out.append(f'<div class="statement {page.type}">\n<div class="lead">{TYPE_LABEL[page.type]}</div>\n{body}\n</div>')
        else:
            out.append(body)
    else:
        ctx.warn("X06", note.body_start + 1, "пустая формулировка")

    for k, h in enumerate(top, 1):
        if h.noexport():
            continue
        kind = heading_kind(h)
        anchor = f"s{k}"
        inner = render_steps(note, h, ctx, 3)
        if not inner.strip():
            ctx.warn("X06", h.line + 1, f"пустой раздел «{h.title}»")
            continue
        if kind == "proof":
            hnote = heading_key(h.title)[1]
            label = "Доказательство" + (f" ({prose_to_html(hnote, ctx, h.line)})" if hnote else "")
            out.append(f'<details class="proof" id="{anchor}">\n<summary>{label} <span class="hint">свёрнуто</span></summary>\n'
                       f'<div class="body">\n{inner}\n</div>\n</details>')
            toc.append((anchor, "Доказательство"))
        else:
            title = heading_title(h, ctx)
            cls = f' class="sec {kind}"' if kind else ' class="sec"'
            out.append(f'<section{cls} id="{anchor}">\n<h2>{title}</h2>\n{inner}\n</section>')
            toc.append((anchor, re.sub(r"<[^>]+>", "", title)))
    out.append('<div class="foot"><span>Файл <code>%s</code></span><span>Изменено %s</span></div>'
               % (esc(rel_of(note)), fmt_date(dt.datetime.fromtimestamp(note.path.stat().st_mtime).strftime("%Y%m%d"))))
    return "\n".join(out), toc, ctx.warnings


def backlinks_html(page: Page, site: Site, root: str) -> str:
    items = []
    seen = set()
    for other, link in site.v.backlinks(page.note):
        op = site.pages.get(other.id)
        if op is None or other.id in seen:
            continue
        seen.add(other.id)
        ctx = HCtx(other, site.v, set(site.pages), site=site, root=root)
        line = mask_links(other.lines[link.line], keep_desc=True).strip()
        snippet = prose_to_html(re.sub(r"\s+", " ", line), ctx, link.line) if line else ""
        snippet = re.sub(r"^\s*(?:[-+]|\d+[.)])\s+", "", snippet)
        items.append(f'<li><a href="{root}{op.url}"><b>{esc(other.title)}</b><span>{snippet}</span></a></li>')
    if not items:
        return '<p class="none">Пока никто не ссылается.</p>'
    return "<ul>\n%s\n</ul>" % "\n".join(items)


