def site_cfg(vault: Vault) -> dict:
    c = dict(vault.cfg.get("site", {}))
    c.setdefault("title", "Заметки")
    c.setdefault("author", "")
    c.setdefault("base_url", "")
    c.setdefault("publish", list(vault.courses))
    c.setdefault("exclude", [])
    c.setdefault("show_status", False)
    c.setdefault("out", "site")
    c.setdefault("intro", "")
    return c


@dataclass
class Page:
    note: Note
    course: str | None
    slug: str
    url: str                      # относительно корня сайта, с завершающим '/'
    stub: bool
    type: str | None
    lecture: "Plan | None" = None  # лекция, в плане которой заметка

    @property
    def id(self) -> str:
        return self.note.id

    @property
    def title(self) -> str:
        return self.note.title

    @property
    def depth(self) -> int:
        return self.url.count("/")


@dataclass
class HCtx(Ctx):
    """Ctx + корень сайта для относительных ссылок."""
    site: "Site | None" = None
    root: str = ""


class Site:
    def __init__(self, vault: Vault, cfg: dict | None = None):
        self.v = vault
        self.cfg = cfg or site_cfg(vault)
        self.warnings: list[DocWarning] = []
        self.courses = [c for c in self.cfg["publish"] if c in vault.courses]
        self.excluded = {x.upper() for x in self.cfg["exclude"]}
        self.pages: dict[str, Page] = {}
        self.plans: dict[str, list[Plan]] = {}
        self.images: set[str] = set()
        self._collect()

    # -- pages ---------------------------------------------------------
    def warn(self, note: Note | None, line: int, code: str, msg: str) -> None:
        self.warnings.append(DocWarning(note.id if note else "", rel_of(note) if note else "", line, code, msg))

    def _collect(self) -> None:
        slugs: dict[str, str] = {}
        for n in self.v.notes:
            if not n.id or n.id in self.excluded:
                continue
            course = self.v.course_of(n)
            if course not in self.courses:
                continue
            slug = n.file_slug or roam.slugify(n.title)
            key = f"{course}/{slug}"
            if key in slugs:
                other = self.v.by_id[slugs[key]]
                self.warn(n, 0, "S01", f"slug «{slug}» совпадает с «{other.title}» -- добавлен суффикс id")
                slug = f"{slug}-{n.id[:6].lower()}"
                key = f"{course}/{slug}"
            slugs[key] = n.id
            ntype = next((t for t in n.tags if t in TYPE_LABEL), None)
            self.pages[n.id] = Page(n, course, slug, f"{course}/{slug}/", self.v.is_stub(n), ntype)
        for n in self.v.notes:
            if n.id and n.id not in self.pages and n.id not in self.excluded and self.v.course_of(n) is None \
                    and not self.v.is_stub(n):
                self.warn(n, 0, "S02", f"«{n.title}» без тега курса -- не публикуется")
        for course in self.courses:
            plans = []
            for ln in lectures_of(self.v, course):
                if ln.id not in self.pages:
                    continue
                plan, w = lecture_plan(ln, self.v)
                self.warnings += w
                for s in plan.sections:
                    s.items = [i for i in s.items if self._plan_ok(i.id, i.line, ln)]
                    for i in s.items:
                        p = self.pages[i.id]
                        if p.lecture is None:
                            p.lecture = plan
                plan.appendix = [i for i in plan.appendix if self._plan_ok(i.id, i.line, ln)]
                plans.append(plan)
            self.plans[course] = plans

    def _plan_ok(self, nid: str, line: int, ln: Note) -> bool:
        if nid in self.pages:
            return True
        if nid not in self.v.by_id:
            self.warn(ln, line, "X03", f"план: битая ссылка id:{nid[:8]}")
        elif nid not in self.excluded:
            self.warn(ln, line, "X07", f"план: «{self.v.by_id[nid].title}» вне публикуемых курсов")
        return False

    def course_name(self, course: str) -> str:
        return self.v.courses[course].get("name", course)

    def off_plan(self, course: str) -> list[Page]:
        planned = {i.id for p in self.plans.get(course, []) for s in p.sections for i in s.items}
        out = [p for p in self.pages.values()
               if p.course == course and p.id not in planned and "lecture" not in p.note.tags]
        return sorted(out, key=lambda p: p.title.casefold())

    def mathjax_macros(self) -> dict:
        mj = {}
        for name, m in roam.load_macros(self.v.cfg).items():
            body = re.sub(r"\\mathds\b", r"\\mathbb", m["body"])
            mj[name.lstrip("\\")] = [body, m["args"]] if m["args"] else body
        return mj


